#!/usr/bin/env node
/* ============================================================
   QOIX — standalone build
   ============================================================
   Inlines styles.css and every js/*.js referenced by index.html
   into a single qoix-standalone.html that runs straight off the
   filesystem — AirDrop it to an iPhone and open it in Safari,
   no local server needed.

   Run: npm run build:standalone
   ============================================================ */

'use strict';

const fs   = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');

// A literal </script> inside inlined JS would close the wrapper early.
const safe = js => js.replace(/<\/script/gi, '<\\/script');

let html = read('index.html');
const inlined = [];

// ── styles.css → <style> ──────────────────────────────────
const linkRe = /[ \t]*<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/?>\s*\n?/i;
const link = html.match(linkRe);
if (!link) {
  console.error('! no stylesheet <link> found in index.html — is the file intact?');
  process.exit(1);
}
html = html.replace(linkRe, '  <style>\n' + read(link[1]) + '\n  </style>\n');
inlined.push(link[1]);

// ── js/*.js → <script> ────────────────────────────────────
html = html.replace(/[ \t]*<script\s+src="([^"]+)"\s*><\/script>\s*\n?/gi, (m, src) => {
  const file = path.join(root, src);
  if (!fs.existsSync(file)) {
    console.error('! missing script referenced by index.html:', src);
    process.exit(1);
  }
  inlined.push(src);
  return '<script>\n/* ── ' + src + ' ── */\n' + safe(read(src)) + '\n</script>\n';
});

if (/<script\s+src=|<link\s+rel="stylesheet"/i.test(html)) {
  console.error('! external references remain after inlining — build is not standalone');
  process.exit(1);
}

// Note for anyone opening the generated file
html = html.replace(/<title>([^<]*)<\/title>/i,
  '<title>$1</title>\n  <!-- Generated by tools/build-standalone.js — edit index.html and the js/ sources, not this file. -->');

const out = path.join(root, 'qoix-standalone.html');
fs.writeFileSync(out, html);

const kb = (fs.statSync(out).size / 1024).toFixed(0);
console.log('qoix-standalone.html  ' + kb + ' KB');
inlined.forEach(f => console.log('  inlined  ' + f));
